#!/usr/bin/env python3
"""Generate TilePivot's icon and store art from ONE geometry definition.

Run from anywhere (Pillow required):  python -I tools/make_store_art.py

Outputs (paths relative to the repo root):
  app/src/main/res/drawable/ic_launcher_background.xml   adaptive background (vector)
  app/src/main/res/drawable/ic_launcher_foreground.xml   adaptive foreground (vector)
  app/src/main/res/mipmap-anydpi-v26/ic_launcher{,_round}.xml
  app/src/main/res/mipmap-{m,h,xh,xxh,xxxh}dpi/ic_launcher{,_round}.png   legacy fallbacks
  store-assets/icon-512.png             Play store icon (full-bleed square, Play masks it)
  store-assets/feature-graphic.png      1024x500 feature graphic

The mark is pure geometry in the launcher's own language: one wide hero panel above a 2x2
grid of smaller tiles, flat, on the app's green. The vectors and the PNGs are drawn from the
same rectangles below, so they can't drift apart. Deterministic: same input, same bytes
(no timestamps or randomness; PNGs are written without metadata).

The feature graphic's wordmark uses Roboto Regular (Apache License 2.0); the script looks for
it in the Windows font folder or a path given in ROBOTO_TTF.
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")
STORE = os.path.join(ROOT, "store-assets")

# ---- the mark (adaptive-icon units: a 108x108 canvas, 66-unit-diameter safe circle) ----------

CANVAS = 108.0
# Background: vertical gradient in the app's green family (the default theme's tile green
# is #008A00; these sit either side of it so the light tiles read clearly).
BG_TOP = (0x12, 0x8A, 0x12)
BG_BOTTOM = (0x05, 0x55, 0x05)
TILE = (0xF2, 0xF2, 0xF2)
SMALL_ALPHA = 0.80          # grid tiles are a touch quieter than the hero
RADIUS = 1.2                # barely softened square corners: flat tiles

# Everything sits in a 44x44 box centred on the canvas, so every corner is inside the
# 33-unit safe radius (corner distance 22*sqrt(2) = 31.1).
BOX = (32.0, 32.0, 76.0, 76.0)
GAP = 3.0
HERO_H = 16.0


def tiles():
    """[(x0, y0, x1, y1, alpha)] for the hero then the 2x2 grid, in canvas units."""
    x0, y0, x1, y1 = BOX
    out = [(x0, y0, x1, y0 + HERO_H, 1.0)]
    grid_top = y0 + HERO_H + GAP
    cell_w = (x1 - x0 - GAP) / 2
    cell_h = (y1 - grid_top - GAP) / 2
    for row in range(2):
        for col in range(2):
            cx = x0 + col * (cell_w + GAP)
            cy = grid_top + row * (cell_h + GAP)
            out.append((cx, cy, cx + cell_w, cy + cell_h, SMALL_ALPHA))
    return out


# ---- vector drawables -------------------------------------------------------------------------

def fmt(v):
    s = ("%.3f" % v).rstrip("0").rstrip(".")
    return s or "0"


def rrect_path(x0, y0, x1, y1, r):
    return (f"M{fmt(x0 + r)},{fmt(y0)} H{fmt(x1 - r)} A{fmt(r)},{fmt(r)} 0 0 1 {fmt(x1)},{fmt(y0 + r)} "
            f"V{fmt(y1 - r)} A{fmt(r)},{fmt(r)} 0 0 1 {fmt(x1 - r)},{fmt(y1)} "
            f"H{fmt(x0 + r)} A{fmt(r)},{fmt(r)} 0 0 1 {fmt(x0)},{fmt(y1 - r)} "
            f"V{fmt(y0 + r)} A{fmt(r)},{fmt(r)} 0 0 1 {fmt(x0 + r)},{fmt(y0)} Z")


def hexrgb(c):
    return "#%02X%02X%02X" % c


HEADER = "<!-- Generated by tools/make_store_art.py; edit the script, not this file. -->\n"


def vector_foreground():
    paths = "\n".join(
        f'    <path\n        android:fillColor="{hexrgb(TILE)}"\n'
        f'        android:fillAlpha="{fmt(a)}"\n'
        f'        android:pathData="{rrect_path(x0, y0, x1, y1, RADIUS)}" />'
        for (x0, y0, x1, y1, a) in tiles())
    return (HEADER +
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            f"{paths}\n</vector>\n")


def vector_background():
    return (HEADER +
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            '    <path android:pathData="M0,0 H108 V108 H0 Z">\n'
            '        <aapt:attr name="android:fillColor">\n'
            '            <gradient\n'
            '                android:type="linear"\n'
            '                android:startX="54" android:startY="0"\n'
            '                android:endX="54" android:endY="108"\n'
            f'                android:startColor="{hexrgb(BG_TOP)}"\n'
            f'                android:endColor="{hexrgb(BG_BOTTOM)}" />\n'
            '        </aapt:attr>\n'
            '    </path>\n'
            '</vector>\n')


ADAPTIVE = (HEADER +
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@drawable/ic_launcher_background" />\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_foreground" />\n'
            '</adaptive-icon>\n')


# ---- raster rendering (supersampled, then downscaled) ----------------------------------------

SS = 8  # supersampling factor


def gradient(w, h, top, bottom):
    img = Image.new("RGB", (w, h))
    px = img.load()
    for y in range(h):
        t = y / max(h - 1, 1)
        c = tuple(round(top[i] + (bottom[i] - top[i]) * t) for i in range(3))
        for x in range(w):
            px[x, y] = c
    return img


def draw_mark(img, scale, ox=0.0, oy=0.0):
    """Draws the tiles onto [img] (RGB) with canvas units scaled by [scale], offset in px."""
    over = Image.new("RGBA", img.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(over)
    for (x0, y0, x1, y1, a) in tiles():
        d.rounded_rectangle(
            [ox + x0 * scale, oy + y0 * scale, ox + x1 * scale - 1, oy + y1 * scale - 1],
            radius=RADIUS * scale, fill=TILE + (round(255 * a),))
    base = img.convert("RGBA")
    base.alpha_composite(over)
    return base.convert("RGB")


def full_icon(px):
    """The flattened adaptive icon (background + mark), full-bleed square, [px] wide."""
    big = px * SS
    img = gradient(big, big, BG_TOP, BG_BOTTOM)
    img = draw_mark(img, big / CANVAS)
    return img.resize((px, px), Image.LANCZOS)


def legacy_icon(px, round_shape):
    """Pre-API-26 launcher icon: the visible centre of the adaptive icon (72 of 108 units),
    masked to a rounded square or a circle with a little margin, like Studio's export."""
    big = px * SS
    margin = round(big * 1.5 / 48)            # 1.5dp of 48dp
    inner = big - 2 * margin
    visible = 72.0                             # what a launcher's mask shows of 108
    scale = inner / visible
    art = gradient(inner, inner, BG_TOP, BG_BOTTOM)
    art = draw_mark(art, scale, ox=-(CANVAS - visible) / 2 * scale, oy=-(CANVAS - visible) / 2 * scale)
    mask = Image.new("L", (inner, inner), 0)
    md = ImageDraw.Draw(mask)
    if round_shape:
        md.ellipse([0, 0, inner - 1, inner - 1], fill=255)
    else:
        md.rounded_rectangle([0, 0, inner - 1, inner - 1], radius=inner * 0.18, fill=255)
    out = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    out.paste(art, (margin, margin), mask)
    return out.resize((px, px), Image.LANCZOS)


def find_roboto():
    env = os.environ.get("ROBOTO_TTF")
    for p in [env, r"C:\Windows\Fonts\Roboto-Regular.ttf", "/usr/share/fonts/truetype/roboto/Roboto-Regular.ttf"]:
        if p and os.path.isfile(p):
            return p
    sys.exit("Roboto-Regular.ttf not found; set ROBOTO_TTF")


def feature_graphic():
    w, h = 1024, 500
    big_w, big_h = w * SS // 2, h * SS // 2   # 4x supersampling keeps the text pass fast
    s = big_w / w
    img = gradient(big_w, big_h, BG_TOP, BG_BOTTOM)
    # The mark at scale on the left: its 44-unit box drawn 300 px tall, vertically centred.
    unit = 300 / 44.0 * s
    box_x0, box_y0 = BOX[0], BOX[1]
    ox = 110 * s - box_x0 * unit
    oy = (h * s - 44 * unit) / 2 - box_y0 * unit
    img = draw_mark(img, unit, ox, oy)
    d = ImageDraw.Draw(img)
    font_path = find_roboto()
    title = ImageFont.truetype(font_path, round(104 * s))
    tag = ImageFont.truetype(font_path, round(34 * s))
    tx = 480 * s
    d.text((tx, 175 * s), "TilePivot", font=title, fill=TILE)
    d.text((tx + 4 * s, 310 * s), "A retro tile launcher", font=tag, fill=(0xD6, 0xEC, 0xD6))
    return img.resize((w, h), Image.LANCZOS)


# ---- write everything ---------------------------------------------------------------------------

def write_text(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, ROOT))


def write_png(path, img):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path, "PNG", optimize=True)
    print("wrote", os.path.relpath(path, ROOT), img.size)


DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def main():
    write_text(os.path.join(RES, "drawable", "ic_launcher_background.xml"), vector_background())
    write_text(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), vector_foreground())
    for name in ("ic_launcher", "ic_launcher_round"):
        write_text(os.path.join(RES, "mipmap-anydpi-v26", name + ".xml"), ADAPTIVE)
    for dens, px in DENSITIES.items():
        write_png(os.path.join(RES, "mipmap-" + dens, "ic_launcher.png"), legacy_icon(px, False))
        write_png(os.path.join(RES, "mipmap-" + dens, "ic_launcher_round.png"), legacy_icon(px, True))
    write_png(os.path.join(STORE, "icon-512.png"), full_icon(512))
    write_png(os.path.join(STORE, "feature-graphic.png"), feature_graphic())


if __name__ == "__main__":
    main()
